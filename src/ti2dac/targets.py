# pySigma backends replaced by a ti2dac subclass that fixes a conversion bug (same backend id and output format).
_BACKEND_FIXES = {"eql": _eql_backend, "loki": _loki_backend}


@lru_cache(maxsize=1)
def plugins():
    from sigma.plugins import InstalledSigmaPlugins

    return InstalledSigmaPlugins.autodiscover()


def resolve_pipeline(names: list[str]):
    from sigma.processing.pipeline import ProcessingPipeline

    resolver = plugins().get_pipeline_resolver()
    pipeline = ProcessingPipeline()
    for n in names:
        pipeline = pipeline + (_LOCAL_PIPELINES[n]() if n in _LOCAL_PIPELINES else resolver.resolve_pipeline(n))
    return pipeline


def _private(pipeline):
    try:
        pipeline = copy.deepcopy(pipeline)
    except TypeError:   # e.g. the Splunk CIM pipeline holds dict_keys; it keeps no state between conversions
        return pipeline
    _fix_pipeline_items(pipeline)
    return pipeline


def _fix_pipeline_items(pipeline) -> None:
    """Plugin pipeline steps with known crashes, swapped for a fixed subclass (on the private copy only).

    pySigma-backend-qradar-aql 0.3: the host-field step calls contains_special() on every value, so a `|cidr`
    value (already a SigmaCIDRExpression) crashed the conversion although the backend has INCIDR()."""
    try:
        from sigma.pipelines.QRadarAQL.QRadarAQL import HostFieldsValueTransformation
        from sigma.types import SigmaString
    except ImportError:
        return

    class StringsOnlyHostFields(HostFieldsValueTransformation):
        def apply_value(self, field, val):
            return super().apply_value(field, val) if isinstance(val, SigmaString) else None

    for item in getattr(pipeline, "items", []):
        if type(item.transformation) is HostFieldsValueTransformation:
            item.transformation.__class__ = StringsOnlyHostFields


def make_backend(target: Target, product: str, client=None):
    """Backend with the target's standard pipelines; a client profile's mapping runs before them."""
    names = target.pipelines_for(product)
    if names is None:
        raise LookupError(f"{target.label} does not support logsource product '{product}'")
    if target.backend in _LOCAL_BACKENDS:
        backend_cls = _LOCAL_BACKENDS[target.backend]()
    elif target.backend in _BACKEND_FIXES:
        backend_cls = _BACKEND_FIXES[target.backend]()
    else:
        backend_cls = plugins().backends.get(target.backend)
    if backend_cls is None:
        raise LookupError(f"pySigma backend '{target.backend}' is not installed")
    # Private copy: some plugins' transformations keep state between conversions (pySigma-kusto appends each
    # error to a shared exception message, so one rule's missing field showed up in the next rule's error).
    pipeline = _private(resolve_pipeline(names)) if names else None
    extra = client.pipeline_for(target.id) if client is not None else None
    if extra is not None:
        pipeline = extra if pipeline is None else extra + pipeline
    return backend_cls(processing_pipeline=pipeline, **target.backend_options)
