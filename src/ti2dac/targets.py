# Regex engines that match the whole value (Sigma `|re` matches anywhere): see regexes.py.
#   lucene   Lucene/OpenSearch query_string, ES|QL RLIKE: anchored, Lucene syntax, no (?i) -> letters case-folded
#   eql      EQL regex/regex~: anchored, Lucene syntax; case-insensitivity via regex~ (kept as the flag)
#   anchored Loki label filters (RE2): anchored only
REGEX_FLAVOR = {"elastic_lucene": "lucene", "opensearch": "lucene", "wazuh_indexer": "lucene",
                "elastic_esql": "lucene", "elastic_eql": "eql", "loki": "anchored"}


def _regex_pipeline(flavor: str):
    def build():
        from dataclasses import dataclass

        from sigma.processing.pipeline import ProcessingItem, ProcessingPipeline
        from sigma.processing.transformations import ValueTransformation
        from sigma.types import SigmaRegularExpression, SigmaRegularExpressionFlag

        from . import regexes

        letter = {"i": SigmaRegularExpressionFlag.IGNORECASE, "m": SigmaRegularExpressionFlag.MULTILINE,
                  "s": SigmaRegularExpressionFlag.DOTALL}

        @dataclass
        class WholeValueRegex(ValueTransformation):
            # No type annotations on apply_value: with postponed annotations pySigma would filter on a string.
            def apply_value(self, field, val):
                if not isinstance(val, SigmaRegularExpression):
                    return None
                inline, pattern = regexes.leading_flags(val.regexp)
                flags = set(val.flags) | {letter[c] for c in inline if c in letter}
                pattern = regexes.anchor(pattern)
                if flavor in ("lucene", "eql"):
                    if flavor == "lucene" and SigmaRegularExpressionFlag.IGNORECASE in flags:
                        pattern = regexes.fold_case(pattern)
                        flags.discard(SigmaRegularExpressionFlag.IGNORECASE)
                    pattern = regexes.to_lucene(pattern)
                    flags -= {SigmaRegularExpressionFlag.MULTILINE, SigmaRegularExpressionFlag.DOTALL}   # Lucene: n/a
                elif inline:
                    pattern = f"(?{inline})" + pattern
                return SigmaRegularExpression(pattern, flags)

        return ProcessingPipeline(name=f"ti2dac whole-value regex ({flavor})", priority=90,
                                  items=[ProcessingItem(identifier=f"ti2dac_regex_{flavor}",
                                                        transformation=WholeValueRegex())])
    return build


def _eql_backend():
    """pySigma-elasticsearch 1.1 writes the regex into an EQL string without doubling backslashes (EQL string
    escapes eat one level, so `\\[a-z]` reached the regex as a literal `[`), and always uses `regex~`."""
    from sigma.backends.elasticsearch import EqlBackend
    from sigma.types import SigmaRegularExpressionFlag

    class Ti2dacEqlBackend(EqlBackend):
        re_escape = ('"',)
        re_escape_escape_char = True
        re_flag_prefix = False

        def convert_condition_field_eq_val_re(self, cond, state):
            op = "regex~" if SigmaRegularExpressionFlag.IGNORECASE in cond.value.flags else "regex"
            return f'{self.escape_and_quote_field(cond.field)} {op} "{self.convert_value_re(cond.value, state)}"'

    return Ti2dacEqlBackend


def _loki_backend():
    """pySigma-loki 0.12 converts a field condition with an expanded value (e.g. `|windash` -> 5 variants, an
    OR) inside an AND without parentheses. LogQL `and` binds tighter than `or`, so `img and cmd1 or cmd2` matched
    cmd2 for any process and skipped the filters."""
    from sigma.backends.loki import LogQLBackend
    from sigma.conditions import ConditionFieldEqualsValueExpression, ConditionOR, ConditionValueExpression
    from sigma.conversion.deferred import DeferredQueryExpression
    from sigma.exceptions import SigmaFeatureNotSupportedByBackendError
    from sigma.types import SigmaExpansion

    class Ti2dacLogQLBackend(LogQLBackend):
        def convert_condition_and(self, cond, state):
            if cond.parent_condition_chain_contains(ConditionOR) and any(
                    isinstance(a, ConditionValueExpression) for a in cond.args):
                raise SigmaFeatureNotSupportedByBackendError(
                    "Operator 'or' not supported by the backend for unbound conditions combined with 'and'",
                    source=cond.source)
            parts = []
            for arg in cond.args:
                expansion = isinstance(arg, ConditionFieldEqualsValueExpression) and isinstance(arg.value, SigmaExpansion)
                if not expansion and (isinstance(arg, (ConditionFieldEqualsValueExpression, ConditionValueExpression))
                                      or self.compare_precedence(cond, arg)):
                    c = self.convert_condition(arg, state)
                else:
                    c = self.convert_condition_group(arg, state)
                if c is not None and not isinstance(c, DeferredQueryExpression) and len(c) > 0:
                    parts.append(c)
            return (self.token_separator + self.and_token + self.token_separator).join(parts)

    return Ti2dacLogQLBackend


